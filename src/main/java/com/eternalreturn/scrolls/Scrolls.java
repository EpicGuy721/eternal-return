package com.eternalreturn.scrolls;

import com.eternalreturn.EternalReturn;
import net.fabricmc.fabric.api.itemgroup.v1.ItemGroupEvents;
import net.minecraft.component.DataComponentTypes;
import net.minecraft.component.type.ItemEnchantmentsComponent;
import net.minecraft.enchantment.Enchantment;
import net.minecraft.entity.player.PlayerEntity;
import net.minecraft.item.Item;
import net.minecraft.item.ItemGroups;
import net.minecraft.item.ItemStack;
import net.minecraft.recipe.RecipeEntry;
import net.minecraft.registry.Registries;
import net.minecraft.registry.Registry;
import net.minecraft.registry.RegistryKey;
import net.minecraft.registry.RegistryKeys;
import net.minecraft.registry.entry.RegistryEntry;
import net.minecraft.server.network.ServerPlayerEntity;
import net.minecraft.sound.SoundCategory;
import net.minecraft.sound.SoundEvents;
import net.minecraft.text.Text;
import net.minecraft.util.Formatting;
import net.minecraft.util.Identifier;
import net.minecraft.util.Rarity;
import org.jetbrains.annotations.Nullable;

import java.util.List;
import java.util.Optional;

/**
 * Scrolls: librarians sell a scroll of an enchantment instead of an enchanted book. Left-clicking with a
 * scroll in the main hand reads it: the scroll is used up and the player learns the recipe for that
 * enchantment's book (eternalreturn:enchanted_book/<enchantment>, generated by tools/scrolls/build_scrolls.py:
 * a book among diamonds, amethyst shards and themed items, making a level I book). Those recipes only
 * craft for a player who has learned them, and never in a crafter.
 */
public final class Scrolls {
	public static final Item SCROLL = Registry.register(Registries.ITEM, EternalReturn.id("scroll"), new ScrollItem(new Item.Settings().maxCount(16).rarity(Rarity.UNCOMMON)));
	public static final String RECIPE_PREFIX = "enchanted_book/";

	private Scrolls() {
	}

	public static void register() {
		ItemGroupEvents.modifyEntriesEvent(ItemGroups.INGREDIENTS).register(entries -> entries.getContext().lookup().getOptionalWrapper(RegistryKeys.ENCHANTMENT)
				.ifPresent(enchantments -> enchantments.streamEntries().forEach(entry -> entries.add(of(entry)))));
	}

	/** A scroll of this enchantment. */
	public static ItemStack of(RegistryEntry<Enchantment> enchantment) {
		ItemStack stack = new ItemStack(SCROLL);
		ItemEnchantmentsComponent.Builder builder = new ItemEnchantmentsComponent.Builder(ItemEnchantmentsComponent.DEFAULT);
		builder.add(enchantment, 1);
		stack.set(DataComponentTypes.STORED_ENCHANTMENTS, builder.build());
		return stack;
	}

	/** The enchantment a scroll teaches, or null. */
	@Nullable
	public static RegistryEntry<Enchantment> enchantment(ItemStack stack) {
		ItemEnchantmentsComponent stored = stack.get(DataComponentTypes.STORED_ENCHANTMENTS);
		return stored == null || stored.isEmpty() ? null : stored.getEnchantments().iterator().next();
	}

	/** The id of the book recipe a scroll of this enchantment teaches. */
	public static Identifier recipeId(RegistryEntry<Enchantment> enchantment) {
		Identifier id = enchantment.getKey().map(RegistryKey::getValue).orElseThrow();
		String path = id.getNamespace().equals("minecraft") ? id.getPath() : id.getNamespace() + "_" + id.getPath();
		return EternalReturn.id(RECIPE_PREFIX + path);
	}

	public static boolean isScrollRecipe(RecipeEntry<?> recipe) {
		return recipe.id().getNamespace().equals(EternalReturn.MOD_ID) && recipe.id().getPath().startsWith(RECIPE_PREFIX);
	}

	/** A player may craft a book recipe only once a scroll has taught it. */
	public static boolean mayCraft(@Nullable PlayerEntity player, RecipeEntry<?> recipe) {
		if (!isScrollRecipe(recipe)) {
			return true;
		}
		return player instanceof ServerPlayerEntity serverPlayer && serverPlayer.getRecipeBook().contains(recipe);
	}

	/**
	 * Reads the scroll in the player's main hand, if that is what they hold: teaches its recipe and uses it
	 * up (creative players keep it). A known recipe isn't taught twice and the scroll is kept.
	 */
	public static void read(ServerPlayerEntity player) {
		ItemStack stack = player.getMainHandStack();
		RegistryEntry<Enchantment> enchantment = stack.isOf(SCROLL) ? enchantment(stack) : null;
		if (enchantment == null) {
			return;
		}
		Text name = enchantment.value().description();
		Optional<RecipeEntry<?>> recipe = player.getServer().getRecipeManager().get(recipeId(enchantment));
		if (recipe.isEmpty()) {
			player.sendMessage(Text.translatable("item.eternalreturn.scroll.unknown", name).formatted(Formatting.GRAY), true);
			return;
		}
		if (player.getRecipeBook().contains(recipe.get())) {
			player.sendMessage(Text.translatable("item.eternalreturn.scroll.known", name).formatted(Formatting.GRAY), true);
			return;
		}
		player.unlockRecipes(List.of(recipe.get()));
		stack.decrementUnlessCreative(1, player);
		player.getWorld().playSound(null, player.getX(), player.getY(), player.getZ(), SoundEvents.ITEM_BOOK_PAGE_TURN, SoundCategory.PLAYERS, 1.0F, 1.0F);
		player.sendMessage(Text.translatable("item.eternalreturn.scroll.learned", name).formatted(Formatting.GOLD), true);
	}

	/** Used by the librarian trade swap: true for treasure enchantments, which cost double. */
	public static boolean isTreasure(RegistryEntry<Enchantment> enchantment) {
		return enchantment.isIn(net.minecraft.registry.tag.EnchantmentTags.TREASURE);
	}
}
