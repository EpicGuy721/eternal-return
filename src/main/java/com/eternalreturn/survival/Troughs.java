/**
 * Troughs (TroughBlock), one of each wood, crafted from five of its slabs in a U; their resources are generated by
 * tools/troughs/build_troughs.py. Hungry animals (AnimalHunger) go to a trough near holding food they eat (entity tags
 * eternalreturn:eats_hay, eats_carrots, eats_seeds) and thirsty ones to one holding water, taking a level each time
 * (FeedGoal); a thirsty animal with no trough near goes to open water. Farmers top troughs up (VillagerChores).
 */
public final class Troughs {
	/** The woods, each with the namespace of its planks and slab. */
	public static final List<String> WOODS = List.of("oak", "spruce", "birch", "jungle", "acacia", "dark_oak", "mangrove", "cherry", "bamboo", "crimson",
			"warped", "eternalreturn:maple", "eternalreturn:pale_oak", "eternalreturn:azalea");
	public static final List<Block> BLOCKS = new ArrayList<>();
	public static final RegistryKey<PointOfInterestType> POI = RegistryKey.of(RegistryKeys.POINT_OF_INTEREST_TYPE, EternalReturn.id("trough"));
	public static final TagKey<EntityType<?>> EATS_HAY = TagKey.of(RegistryKeys.ENTITY_TYPE, EternalReturn.id("eats_hay"));
	public static final TagKey<EntityType<?>> EATS_CARROTS = TagKey.of(RegistryKeys.ENTITY_TYPE, EternalReturn.id("eats_carrots"));
	public static final TagKey<EntityType<?>> EATS_SEEDS = TagKey.of(RegistryKeys.ENTITY_TYPE, EternalReturn.id("eats_seeds"));
	/** How far an animal goes for a trough. */
	public static final int RANGE = 16;

	static {
		for (String wood : WOODS) {
			Identifier id = Identifier.of(wood);
			Block planks = Registries.BLOCK.get(id.withPath(id.getPath() + "_planks"));
			Block trough = Registry.register(Registries.BLOCK, EternalReturn.id(id.getPath() + "_trough"), new TroughBlock(AbstractBlock.Settings.copy(Blocks.COMPOSTER)
					.mapColor(planks.getDefaultMapColor()).sounds(planks.getDefaultState().getSoundGroup())));
			Registry.register(Registries.ITEM, EternalReturn.id(id.getPath() + "_trough"), new BlockItem(trough, new Item.Settings()));
			BLOCKS.add(trough);
		}
	}

	private Troughs() {
	}

	public static void register() {
		PointOfInterestHelper.register(POI.getValue(), 0, 1, BLOCKS.toArray(Block[]::new));
		FlammableBlockRegistry flammable = FlammableBlockRegistry.getDefaultInstance();
		for (int i = 0; i < WOODS.size(); i++) {
			if (!WOODS.get(i).equals("crimson") && !WOODS.get(i).equals("warped")) {
				flammable.add(BLOCKS.get(i), 5, 20);
			}
		}
		ItemGroupEvents.modifyEntriesEvent(ItemGroups.FUNCTIONAL).register(entries -> entries.addAfter(Items.COMPOSTER,
				BLOCKS.stream().map(Block::asItem).toArray(Item[]::new)));
	}

	/** Whether the animal eats or drinks this from a trough. */
	public static boolean wants(AnimalEntity animal, TroughBlock.Contents contents) {
		return switch (contents) {
			case WATER -> AnimalHunger.thirsts(animal);
			case HAY -> animal.getType().isIn(EATS_HAY);
			case CARROTS -> animal.getType().isIn(EATS_CARROTS);
			case SEEDS -> animal.getType().isIn(EATS_SEEDS);
			case NONE -> false;
		};
	}

	/** The nearest trough within range whose state is wanted, or null. */
	@Nullable
	public static BlockPos nearest(ServerWorld world, BlockPos from, int range, Predicate<BlockState> wanted) {
		return world.getPointOfInterestStorage()
				.getInSquare(type -> type.matchesKey(POI), from, range, PointOfInterestStorage.OccupationStatus.ANY)
				.map(PointOfInterest::getPos)
				.filter(pos -> wanted.test(world.getBlockState(pos)))
				.min(Comparator.comparingDouble(pos -> pos.getSquaredDistance(from)))
				.orElse(null);
	}

	/**
	 * A hungry or thirsty animal goes to a trough near with what it wants in it (thirst first) and eats or drinks a
	 * level; thirsty with no water trough near, it goes to the edge of open water and drinks there.
	 */
	public static class FeedGoal extends Goal {
		private final AnimalEntity animal;
		@Nullable
		private BlockPos trough;
		@Nullable
		private BlockPos waterside;
		private boolean drinking;
		private int ticks;
		private int eating;

		public FeedGoal(AnimalEntity animal) {
			this.animal = animal;
			this.setControls(EnumSet.of(Goal.Control.MOVE, Goal.Control.LOOK));
		}

		@Override
		public boolean canStart() {
			if (!(this.animal.getWorld() instanceof ServerWorld world) || this.animal.getRandom().nextInt(20) != 0) {
				return false;
			}
			this.trough = null;
			this.waterside = null;
			BlockPos at = this.animal.getBlockPos();
			if (AnimalHunger.isThirsty(this.animal)) {
				if (AnimalHunger.canDrinkHere(this.animal)) {
					AnimalHunger.watered(this.animal);
					return false;
				}
				this.drinking = true;
				this.trough = nearest(world, at, RANGE, state -> TroughBlock.holds(state, TroughBlock.Contents.WATER));
				if (this.trough == null) {
					this.waterside = AnimalHunger.findWaterside(this.animal, 24);
				}
				if (this.trough != null || this.waterside != null) {
					return true;
				}
			}
			if (AnimalHunger.isHungry(this.animal)) {
				this.drinking = false;
				this.trough = nearest(world, at, RANGE, state -> state.getBlock() instanceof TroughBlock && state.get(TroughBlock.LEVEL) > 0
						&& state.get(TroughBlock.CONTENTS) != TroughBlock.Contents.WATER && wants(this.animal, state.get(TroughBlock.CONTENTS)));
			}
			return this.trough != null;
		}

		@Override
		public boolean shouldContinue() {
			if (this.ticks >= 400 || !(this.drinking ? AnimalHunger.isThirsty(this.animal) : AnimalHunger.isHungry(this.animal))) {
				return false;
			}
			if (this.trough == null) {
				return true;
			}
			BlockState state = this.animal.getWorld().getBlockState(this.trough);
			return state.getBlock() instanceof TroughBlock && state.get(TroughBlock.LEVEL) > 0
					&& (state.get(TroughBlock.CONTENTS) == TroughBlock.Contents.WATER) == this.drinking;
		}

		@Override
		public void start() {
			this.ticks = 0;
			this.eating = 0;
			this.moveOn();
		}

		@Override
		public void stop() {
			this.animal.getNavigation().stop();
		}

		@Override
		public boolean shouldRunEveryTick() {
			return true;
		}

		private BlockPos target() {
			return this.trough != null ? this.trough : this.waterside;
		}

		private void moveOn() {
			BlockPos target = this.target();
			this.animal.getNavigation().startMovingTo(target.getX() + 0.5, target.getY(), target.getZ() + 0.5, 1.0);
		}

		@Override
		public void tick() {
			this.ticks++;
			BlockPos target = this.target();
			Vec3d center = Vec3d.ofBottomCenter(target);
			boolean there;
			if (this.trough != null) {
				double dx = center.x - this.animal.getX();
				double dz = center.z - this.animal.getZ();
				double reach = 1.0 + this.animal.getWidth() / 2.0;
				there = dx * dx + dz * dz <= reach * reach && Math.abs(center.y - this.animal.getY()) < 1.5;
			} else {
				there = AnimalHunger.canDrinkHere(this.animal);
			}
			if (!there) {
				this.eating = 0;
				if (this.ticks % 20 == 0) {
					this.moveOn();
				}
				return;
			}
			this.animal.getNavigation().stop();
			this.animal.getLookControl().lookAt(center.x, center.y + 0.3, center.z);
			if (++this.eating < 30) {
				return;
			}
			if (this.trough != null && this.animal.getWorld() instanceof ServerWorld world) {
				BlockState state = world.getBlockState(this.trough);
				BlockState shown = switch (state.get(TroughBlock.CONTENTS)) {
					case HAY -> Blocks.HAY_BLOCK.getDefaultState();
					case CARROTS -> Blocks.CARROTS.getDefaultState();
					case SEEDS -> Blocks.WHEAT.getDefaultState();
					default -> Blocks.WATER.getDefaultState();
				};
				world.spawnParticles(new BlockStateParticleEffect(ParticleTypes.BLOCK, shown), center.x, center.y + 0.5, center.z, 6, 0.2, 0.1, 0.2, 0.0);
				TroughBlock.take(world, this.trough);
			}
			if (this.drinking) {
				this.animal.playSound(SoundEvents.ENTITY_GENERIC_DRINK, 0.6F, 1.0F);
				AnimalHunger.watered(this.animal);
			} else {
				this.animal.playSound(SoundEvents.ENTITY_GENERIC_EAT, 0.8F, 1.0F);
				AnimalHunger.fed(this.animal);
			}
			this.ticks = 400;
		}
	}
}
