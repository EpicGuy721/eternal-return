package com.eternalreturn.blocks;

import com.eternalreturn.EternalReturn;
import com.eternalreturn.worldgen.stone.NamedBlockItem;
import net.fabricmc.fabric.api.itemgroup.v1.ItemGroupEvents;
import net.fabricmc.fabric.api.registry.FlammableBlockRegistry;
import net.minecraft.block.AbstractBlock;
import net.minecraft.block.Block;
import net.minecraft.block.SlabBlock;
import net.minecraft.block.StairsBlock;
import net.minecraft.item.ItemGroups;
import net.minecraft.registry.Registries;
import net.minecraft.registry.Registry;
import net.minecraft.text.MutableText;
import net.minecraft.text.Text;
import net.minecraft.util.DyeColor;
import net.minecraft.util.Identifier;

import java.util.ArrayList;
import java.util.List;

/**
 * Stairs and slabs of every color of wool and concrete (eternalreturn:white_wool_stairs,
 * eternalreturn:white_concrete_slab and so on), each with the look, sound, hardness and tool of its full
 * block: wool burns and is quick with shears, concrete needs a pickaxe. Their names are built from the
 * full block's name ("White Wool" + " Stairs"). Models, blockstates, loot tables, recipes and tags are
 * generated by tools/blocks/build_blocks.py.
 */
public final class CutBlocks {
	public static final String[] MATERIALS = {"wool", "concrete"};

	public record Variant(Block base, Block stairs, Block slab, boolean wool) {
	}

	public static final List<Variant> ALL = new ArrayList<>();

	static {
		for (DyeColor color : DyeColor.values()) {
			for (String material : MATERIALS) {
				String id = color.getName() + "_" + material;
				Block base = Registries.BLOCK.get(Identifier.ofVanilla(id));
				Block stairs = register(id + "_stairs", new Stairs(base, AbstractBlock.Settings.copy(base)));
				Block slab = register(id + "_slab", new Slab(base, AbstractBlock.Settings.copy(base)));
				ALL.add(new Variant(base, stairs, slab, material.equals("wool")));
			}
		}
	}

	private CutBlocks() {
	}

	public static void register() {
		for (Variant variant : ALL) {
			if (variant.wool()) {
				// Wool's own flammability (catches 30, burns 60).
				FlammableBlockRegistry.getDefaultInstance().add(variant.stairs(), 30, 60);
				FlammableBlockRegistry.getDefaultInstance().add(variant.slab(), 30, 60);
			}
		}
		ItemGroupEvents.modifyEntriesEvent(ItemGroups.COLORED_BLOCKS).register(entries -> {
			for (Variant variant : ALL) {
				entries.addAfter(variant.base(), variant.stairs(), variant.slab());
			}
		});
	}

	private static Block register(String id, Block block) {
		Registry.register(Registries.BLOCK, EternalReturn.id(id), block);
		Registry.register(Registries.ITEM, EternalReturn.id(id), new NamedBlockItem(block));
		return block;
	}

	private static final class Stairs extends StairsBlock {
		private final Block base;

		Stairs(Block base, AbstractBlock.Settings settings) {
			super(base.getDefaultState(), settings);
			this.base = base;
		}

		@Override
		public MutableText getName() {
			return Text.translatable("block.eternalreturn.stairs", this.base.getName());
		}
	}

	private static final class Slab extends SlabBlock {
		private final Block base;

		Slab(Block base, AbstractBlock.Settings settings) {
			super(settings);
			this.base = base;
		}

		@Override
		public MutableText getName() {
			return Text.translatable("block.eternalreturn.slab", this.base.getName());
		}
	}
}
