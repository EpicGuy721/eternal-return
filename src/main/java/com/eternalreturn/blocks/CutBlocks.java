package com.eternalreturn.blocks;

import com.eternalreturn.EternalReturn;
import com.eternalreturn.worldgen.stone.NamedBlockItem;
import net.fabricmc.fabric.api.itemgroup.v1.ItemGroupEvents;
import net.fabricmc.fabric.api.registry.FlammableBlockRegistry;
import net.minecraft.block.AbstractBlock;
import net.minecraft.block.Block;
import net.minecraft.block.SlabBlock;
import net.minecraft.block.StairsBlock;
import net.minecraft.block.WallBlock;
import net.minecraft.item.ItemGroups;
import net.minecraft.registry.Registries;
import net.minecraft.registry.Registry;
import net.minecraft.text.MutableText;
import net.minecraft.text.Text;
import net.minecraft.util.DyeColor;
import net.minecraft.util.Identifier;

import java.util.ArrayList;
import java.util.List;

/**
 * Stairs and slabs of every color of wool and concrete (eternalreturn:white_wool_stairs,
 * eternalreturn:white_concrete_slab and so on), each with the look, sound, hardness and tool of its full
 * block: wool burns and is quick with shears, concrete needs a pickaxe. Their names are built from the
 * full block's name ("White Wool" + " Stairs"). Models, blockstates, loot tables, recipes and tags are
 * generated by tools/blocks/build_blocks.py.
 * <p>
 * And so that every stone-like block with stairs and a slab has a wall too (and the other way round), walls of the
 * stone-like families vanilla gives none (STONE_WALLS: eternalreturn:stone_wall, eternalreturn:quartz_wall...), and
 * stairs for the three with a slab but no stairs (MORE_STAIRS: smooth stone, cut sandstone, cut red sandstone). Like
 * every wall they hold snow (SnowCover). Their resources come from the same script; its tables must match these.
 */
public final class CutBlocks {
	public static final String[] MATERIALS = {"wool", "concrete"};

	public record Variant(Block base, Block stairs, Block slab, boolean wool) {
	}

	public static final List<Variant> ALL = new ArrayList<>();

	/** A new wall or stairs of a vanilla block (base), shown after vanilla's block in the creative tab (after). */
	public record Extra(Block base, Block block, Block after) {
	}

	/** Wall id -> the vanilla block it's made of, and the vanilla block it follows in the creative tab. */
	private static final String[][] STONE_WALL_TABLE = {
			{"stone_wall", "stone", "stone_slab"},
			{"smooth_stone_wall", "smooth_stone", "smooth_stone_slab"},
			{"polished_granite_wall", "polished_granite", "polished_granite_slab"},
			{"polished_diorite_wall", "polished_diorite", "polished_diorite_slab"},
			{"polished_andesite_wall", "polished_andesite", "polished_andesite_slab"},
			{"cut_sandstone_wall", "cut_sandstone", "cut_sandstone_slab"},
			{"smooth_sandstone_wall", "smooth_sandstone", "smooth_sandstone_slab"},
			{"cut_red_sandstone_wall", "cut_red_sandstone", "cut_red_sandstone_slab"},
			{"smooth_red_sandstone_wall", "smooth_red_sandstone", "smooth_red_sandstone_slab"},
			{"quartz_wall", "quartz_block", "quartz_slab"},
			{"smooth_quartz_wall", "smooth_quartz", "smooth_quartz_slab"},
			{"purpur_wall", "purpur_block", "purpur_slab"},
			{"prismarine_brick_wall", "prismarine_bricks", "prismarine_brick_slab"},
			{"dark_prismarine_wall", "dark_prismarine", "dark_prismarine_slab"},
	};
	/** Stairs id -> the vanilla block, and the block they follow in the creative tab. */
	private static final String[][] MORE_STAIRS_TABLE = {
			{"smooth_stone_stairs", "smooth_stone", "smooth_stone"},
			{"cut_sandstone_stairs", "cut_sandstone", "cut_sandstone"},
			{"cut_red_sandstone_stairs", "cut_red_sandstone", "cut_red_sandstone"},
	};
	public static final List<Extra> STONE_WALLS = new ArrayList<>();
	public static final List<Extra> MORE_STAIRS = new ArrayList<>();

	static {
		for (DyeColor color : DyeColor.values()) {
			for (String material : MATERIALS) {
				String id = color.getName() + "_" + material;
				Block base = Registries.BLOCK.get(Identifier.ofVanilla(id));
				Block stairs = register(id + "_stairs", new Stairs(base, AbstractBlock.Settings.copy(base)));
				Block slab = register(id + "_slab", new Slab(base, AbstractBlock.Settings.copy(base)));
				ALL.add(new Variant(base, stairs, slab, material.equals("wool")));
			}
		}
		for (String[] row : STONE_WALL_TABLE) {
			Block base = Registries.BLOCK.get(Identifier.ofVanilla(row[1]));
			// As vanilla's walls: the full block's settings, made solid (walls are, for mobs and suffocation).
			Block wall = register(row[0], new WallBlock(AbstractBlock.Settings.copy(base).solid()));
			STONE_WALLS.add(new Extra(base, wall, Registries.BLOCK.get(Identifier.ofVanilla(row[2]))));
		}
		for (String[] row : MORE_STAIRS_TABLE) {
			Block base = Registries.BLOCK.get(Identifier.ofVanilla(row[1]));
			Block stairs = register(row[0], new Stairs(base, AbstractBlock.Settings.copy(base)));
			MORE_STAIRS.add(new Extra(base, stairs, Registries.BLOCK.get(Identifier.ofVanilla(row[2]))));
		}
	}

	private CutBlocks() {
	}

	public static void register() {
		for (Variant variant : ALL) {
			if (variant.wool()) {
				// Wool's own flammability (catches 30, burns 60).
				FlammableBlockRegistry.getDefaultInstance().add(variant.stairs(), 30, 60);
				FlammableBlockRegistry.getDefaultInstance().add(variant.slab(), 30, 60);
			}
		}
		ItemGroupEvents.modifyEntriesEvent(ItemGroups.COLORED_BLOCKS).register(entries -> {
			for (Variant variant : ALL) {
				entries.addAfter(variant.base(), variant.stairs(), variant.slab());
			}
		});
		ItemGroupEvents.modifyEntriesEvent(ItemGroups.BUILDING_BLOCKS).register(entries -> {
			for (Extra extra : MORE_STAIRS) {
				entries.addAfter(extra.after(), extra.block());
			}
			for (Extra extra : STONE_WALLS) {
				entries.addAfter(extra.after(), extra.block());
			}
		});
	}

	private static Block register(String id, Block block) {
		Registry.register(Registries.BLOCK, EternalReturn.id(id), block);
		Registry.register(Registries.ITEM, EternalReturn.id(id), new NamedBlockItem(block));
		return block;
	}

	private static final class Stairs extends StairsBlock {
		private final Block base;

		Stairs(Block base, AbstractBlock.Settings settings) {
			super(base.getDefaultState(), settings);
			this.base = base;
		}

		@Override
		public MutableText getName() {
			return Text.translatable("block.eternalreturn.stairs", this.base.getName());
		}
	}

	private static final class Slab extends SlabBlock {
		private final Block base;

		Slab(Block base, AbstractBlock.Settings settings) {
			super(settings);
			this.base = base;
		}

		@Override
		public MutableText getName() {
			return Text.translatable("block.eternalreturn.slab", this.base.getName());
		}
	}
}
