package com.eternalreturn.items;

import com.eternalreturn.EternalReturn;
import net.fabricmc.fabric.api.item.v1.DefaultItemComponentEvents;
import net.minecraft.component.DataComponentTypes;
import net.minecraft.item.Item;
import net.minecraft.item.Items;
import net.minecraft.registry.Registries;
import net.minecraft.registry.RegistryKeys;
import net.minecraft.registry.tag.TagKey;

import java.util.Map;

/**
 * Horse armor (eternalreturn:horse_armor) wears out like a rider's: it lasts as long as a chestplate of its material and
 * takes damage as the horse is hurt (HorseArmorDamageMixin). It takes the protections, Unbreaking and Frost Walker,
 * working in the slot the horse wears it in (data/minecraft/enchantment, generated by
 * tools/enchantments/build_horse_armor.py), at a table (HorseArmorEnchantableMixin) or an anvil, with the enchant
 * capacity of its material (eternalreturn:enchant_cap/*).
 */
public final class HorseArmor {
	public static final TagKey<Item> TAG = TagKey.of(RegistryKeys.ITEM, EternalReturn.id("horse_armor"));

	private HorseArmor() {
	}

	private static Item item(String name) {
		return Registries.ITEM.get(EternalReturn.id(name));
	}

	public static void register() {
		Map<Item, Item> chestplates = Map.of(
				Items.LEATHER_HORSE_ARMOR, Items.LEATHER_CHESTPLATE,
				Items.IRON_HORSE_ARMOR, Items.IRON_CHESTPLATE,
				Items.GOLDEN_HORSE_ARMOR, Items.GOLDEN_CHESTPLATE,
				Items.DIAMOND_HORSE_ARMOR, Items.DIAMOND_CHESTPLATE,
				item("copper_horse_armor"), item("copper_chestplate"),
				item("rosegold_horse_armor"), item("rosegold_chestplate"));
		DefaultItemComponentEvents.MODIFY.register(context -> chestplates.forEach((armor, chestplate) -> {
			int durability = chestplate.getComponents().getOrDefault(DataComponentTypes.MAX_DAMAGE, 0);
			context.modify(armor, builder -> builder.add(DataComponentTypes.MAX_DAMAGE, durability).add(DataComponentTypes.DAMAGE, 0));
		}));
	}
}
