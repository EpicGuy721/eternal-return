package com.eternalreturn.client;

import com.eternalreturn.EternalReturn;
import com.eternalreturn.blocks.Frames;
import net.fabricmc.fabric.api.client.model.loading.v1.ModelLoadingPlugin;
import net.fabricmc.fabric.api.client.rendering.v1.ColorProviderRegistry;
import net.fabricmc.fabric.api.client.rendering.v1.EntityRendererRegistry;
import net.minecraft.client.item.ModelPredicateProviderRegistry;
import net.minecraft.client.render.entity.ItemFrameEntityRenderer;
import net.minecraft.client.render.model.BakedModel;
import net.minecraft.client.render.model.BakedModelManager;
import net.minecraft.component.DataComponentTypes;
import net.minecraft.component.type.DyedColorComponent;
import net.minecraft.item.Item;
import net.minecraft.item.Items;
import net.minecraft.util.Identifier;

/**
 * Client side of glass and dyed item frames (Frames): the glass frame and dyed frame models, renderers, and dyed item
 * icons. Dye colours the leather back only (the glass frames' back), over grey copies of it, as Fast Item Frames does:
 * a dyed frame draws eternalreturn:block/dyed_<frame> (ItemFrameEntityRendererMixin), an undyed one vanilla's. Item
 * icons are two layers, the frame and the inside (dyed); vanilla's frames, and the glowing glass one, switch to a
 * grey inside when dyed (the eternalreturn:dyed model predicate). All generated by tools/frames/build_frames.py.
 */
public final class FrameModels {
	public static final Identifier GLASS_FRAME = EternalReturn.id("block/glass_item_frame");
	public static final Identifier GLOWING_GLASS_FRAME = EternalReturn.id("block/glowing_glass_item_frame");
	private static final Identifier DYED_FRAME = EternalReturn.id("block/dyed_item_frame");
	private static final Identifier DYED_MAP_FRAME = EternalReturn.id("block/dyed_item_frame_map");
	private static final Identifier DYED_GLOW_FRAME = EternalReturn.id("block/dyed_glow_item_frame");
	private static final Identifier DYED_MAP_GLOW_FRAME = EternalReturn.id("block/dyed_glow_item_frame_map");

	private FrameModels() {
	}

	public static void register() {
		ModelLoadingPlugin.register(context -> context.addModels(GLASS_FRAME, GLOWING_GLASS_FRAME, DYED_FRAME, DYED_MAP_FRAME, DYED_GLOW_FRAME,
				DYED_MAP_GLOW_FRAME));
		EntityRendererRegistry.register(Frames.GLASS_ITEM_FRAME, ItemFrameEntityRenderer::new);
		EntityRendererRegistry.register(Frames.GLOWING_GLASS_ITEM_FRAME, ItemFrameEntityRenderer::new);
		// Layer 1 is the inside (the frame is layer 0 and keeps its colours).
		ColorProviderRegistry.ITEM.register((stack, tintIndex) -> tintIndex == 1 ? DyedColorComponent.getColor(stack, -1) : -1,
				Items.ITEM_FRAME, Items.GLOW_ITEM_FRAME, Frames.GLASS_ITEM_FRAME_ITEM, Frames.GLOWING_GLASS_ITEM_FRAME_ITEM);
		for (Item item : new Item[] {Items.ITEM_FRAME, Items.GLOW_ITEM_FRAME, Frames.GLOWING_GLASS_ITEM_FRAME_ITEM}) {
			ModelPredicateProviderRegistry.register(item, EternalReturn.id("dyed"),
					(stack, world, entity, seed) -> stack.contains(DataComponentTypes.DYED_COLOR) ? 1.0F : 0.0F);
		}
	}

	/** A glass frame's model: the glowing one's own back unless dyed (a dyed one is grey under the dye, as the other). */
	public static BakedModel glassFrame(BakedModelManager models, boolean glowing, boolean dyed) {
		return models.getModel(glowing && !dyed ? GLOWING_GLASS_FRAME : GLASS_FRAME);
	}

	public static BakedModel dyedFrame(BakedModelManager models, boolean glow, boolean map) {
		return models.getModel(glow ? map ? DYED_MAP_GLOW_FRAME : DYED_GLOW_FRAME : map ? DYED_MAP_FRAME : DYED_FRAME);
	}
}
